const getTodayStr = (): string => {
  const d = new Date();
  return d.toISOString().split('T')[0];
};

const getRelativeDate = (offsetDays: number): string => {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().split('T')[0];
};

